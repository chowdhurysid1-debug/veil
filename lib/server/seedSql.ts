import {
  SEED_FILENAME_PREFIX,
  SEED_LABELS,
  SEED_SITES,
  seedId,
  seedOffset,
} from "../learning/seed";

// Seed clips never existed as video, so their hashes and signatures are inert placeholders.
const PLACEHOLDER_SHA256 = "0".repeat(64);

function sqlString(value: string | null): string {
  return value === null ? "null" : `'${value.replaceAll("'", "''")}'`;
}

function seedTimestamp(index: number, daysAgo: number): string {
  const { days, hours, minutes } = seedOffset(index, daysAgo);
  return `date_trunc('day', now(), 'UTC') + make_interval(days => ${days}, hours => ${hours}, mins => ${minutes})`;
}

function insert(table: string, columns: string[], rows: string[][]): string {
  const values = rows.map((row) => `  (${row.join(", ")})`).join(",\n");
  return `insert into public.${table} (${columns.join(", ")})\nvalues\n${values}\non conflict do nothing;\n`;
}

export function buildSeedSql(): string {
  const sites = SEED_SITES.map((site) => [
    sqlString(site.id),
    sqlString(site.name),
    sqlString(site.kind),
  ]);

  const clips = SEED_SITES.map((site, index) => [
    sqlString(seedId("clips", index + 1)),
    sqlString(site.id),
    sqlString(`${SEED_FILENAME_PREFIX}${site.kind}.mp4`),
    sqlString(PLACEHOLDER_SHA256),
    sqlString("seed-data-not-signed"),
    seedTimestamp(0, 7),
    "1",
  ]);

  const frames = SEED_SITES.map((_site, index) => [
    sqlString(seedId("frames", index + 1)),
    sqlString(seedId("clips", index + 1)),
    "0",
    "0",
    sqlString("seed-data/no-frame.jpg"),
    sqlString(PLACEHOLDER_SHA256),
  ]);

  const events = SEED_LABELS.map((seed, index) => [
    sqlString(seedId("events", index + 1)),
    sqlString(seedId("clips", seed.siteIndex + 1)),
    sqlString(seedId("frames", seed.siteIndex + 1)),
    sqlString(seed.type),
    seed.label === "real" ? "0.8" : "0.65",
    sqlString(seed.description),
    "true",
    seedTimestamp(index, seed.daysAgo),
  ]);

  const feedback = SEED_LABELS.map((seed, index) => [
    sqlString(seedId("feedback", index + 1)),
    sqlString(seedId("events", index + 1)),
    sqlString(SEED_SITES[seed.siteIndex].id),
    sqlString(seed.label),
    sqlString(seed.note),
    seedTimestamp(index, seed.daysAgo),
  ]);

  return [
    "-- Generated by scripts/seed-sql.mts from lib/learning/seed.ts. Do not edit by hand.",
    "-- Safe to run more than once: every row has a fixed id and existing rows are skipped.",
    `-- Seed rows are fake demo data. Their ids start with 5eed and seed clip filenames start with "${SEED_FILENAME_PREFIX}".`,
    "",
    insert("sites", ["id", "name", "kind"], sites),
    insert(
      "clips",
      [
        "id",
        "site_id",
        "filename",
        "sha256",
        "signature",
        "captured_at",
        "frame_count",
      ],
      clips,
    ),
    insert(
      "frames",
      ["id", "clip_id", "frame_index", "t_seconds", "blurred_path", "sha256"],
      frames,
    ),
    insert(
      "events",
      [
        "id",
        "clip_id",
        "frame_id",
        "type",
        "confidence",
        "description",
        "flagged",
        "created_at",
      ],
      events,
    ),
    insert(
      "feedback",
      ["id", "event_id", "site_id", "label", "note", "created_at"],
      feedback,
    ),
  ].join("\n");
}
